def test_every_article_sha256_matches_its_text():
    """The hash must certify the operative article text, not an amendment note."""
    import hashlib

    for stem in (
        "labor-law", "civil-transactions-law", "pdpl", "pdpl-exec-regulations",
        "commercial-courts", "companies-law", "arbitration-law", "e-commerce-law",
    ):
        corpus = _load(stem)
        mismatches = []
        for article in corpus["articles"]:
            actual = hashlib.sha256(article["text"].encode("utf-8")).hexdigest()
            if actual != article["sha256"]:
                mismatches.append(article["article"])
        assert mismatches == [], f"{stem}: {mismatches}"


def test_every_corpus_article_is_non_empty_and_html_free():
    for stem in (
        "labor-law", "civil-transactions-law", "pdpl", "pdpl-exec-regulations",
        "commercial-courts", "companies-law", "arbitration-law", "e-commerce-law",
    ):
        corpus = _load(stem)
        for article in corpus["articles"]:
            assert article["text"].strip(), f"{stem} article {article['article']} is empty"
            assert not re.search(r"<[^>]+>", article["text"]), (
                f"{stem} article {article['article']} contains HTML"
            )
            assert article["text_origin"] == TEXT_ORIGIN_OFFICIAL
            assert article["sha256"]


def test_search_end_of_service_returns_article_84_quote_not_summary_row():
    result = search_legal_provision(
        "مكافأة نهاية الخدمة",
        "labor-law",
    )
    assert result["insufficient_evidence"] is False
    assert result.get("retrieval_scope") == "verbatim_corpus"
    quote = next(
        (q for q in result.get("quotes", []) if q.get("article") == "84"),
        None,
    )
    assert quote is not None, [q.get("article") for q in result.get("quotes", [])]
    assert quote["text_origin"] == TEXT_ORIGIN_OFFICIAL
    assert "نصف شهر" in quote["text"]
    assert quote["provenance_level"] in ("fetched_official", "article_level")
    assert any(c["link_type"] == LINK_DOCUMENT for c in quote["citations"])
    assert quote["fetched_at"]

    answer = result["answer_markdown"]
    assert "نصف شهر" in answer
    assert "laws.boe.gov.sa" in answer
    assert "استشارة قانونية" in answer
    assert "اقتباس حرفي" in answer

    # Top-level provenance must not repeat the same document link per quote.
    urls = [c["url"] for c in result["provenance"]["links"]]
    assert urls
    assert len(urls) == len(set(urls))


def test_no_amendment_instruction_is_stored_as_article_text():
    """BOE exposes some added articles as an instruction ("إضافة مادة ...").
    The stored `text` must be the operative quoted text, not the instruction."""
    markers = ("ليكون النص", "لتكون بالنص", "إضافة مادة", "أضيفت هذه المادة")
    corpus = _load("labor-law")
    offenders = [
        a["article"] for a in corpus["articles"]
        if any(marker in a.get("text", "") for marker in markers)
    ]
    assert offenders == []

    expected = {
        "233": "للوزير منح مكافأة مالية",
        "234": "لا تقبل أمام المحاكم العمالية",
        "235": "لا يجوز لصاحب العمل أثناء نظر الدعوى",
    }
    for number, phrase in expected.items():
        article = get_article("labor-law", number)
        assert article is not None
        assert phrase in article["text"]
        # The original instruction must remain in amendment_history.
        assert article.get("amendment_history"), number
        history = re.sub(r"[\u064B-\u0652\u0670]", "", article["amendment_history"])
        assert (
            "أضيفت هذه المادة" in history
            or "إضافة مادة" in history
        ), number


def test_every_amended_or_added_article_has_an_instrument():
    corpus = _load("labor-law")
    missing = [
        a["article"] for a in corpus["articles"]
        if a.get("status") in ("amended", "added")
        and not a.get("amendment_instruments")
    ]
    assert missing == []

    missing_history = [
        a["article"] for a in corpus["articles"]
        if a.get("status") in ("amended", "added")
        and not a.get("amendment_history")
    ]
    assert missing_history == []

    malformed = []
    for article in corpus["articles"]:
        for item in article.get("amendment_instruments", []):
            if " " in item["instrument"] or not re.match(
                r"^\d{4}/\d{1,2}/\d{1,2}$", item["date"]
            ):
                malformed.append((article["article"], item))
    assert malformed == []


