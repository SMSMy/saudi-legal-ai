def test_summary_is_marked_hand_written_and_never_quoted_as_official():
    summary = read_source("labor-law", section="مكافأة نهاية الخدمة")
    assert summary["text_origin"] == TEXT_ORIGIN_HAND_WRITTEN
    assert summary["quotes"] == []
    assert summary["provenance_level"] in ("linked_document", "linked_portal")

    result = search_legal_provision("مكافأة نهاية الخدمة", "labor-law")
    assert result["text_origin"] == TEXT_ORIGIN_OFFICIAL
    # The summary text may appear only as commentary/matched_sections; every
    # item in quotes must be verbatim.
    for quote in result.get("quotes", []):
        assert quote["text_origin"] == TEXT_ORIGIN_OFFICIAL


