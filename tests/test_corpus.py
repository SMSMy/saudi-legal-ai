CORPUS = get_repo_path() / "corpus"


def _load(stem: str) -> dict:
    path = CORPUS / f"{stem}.json"
    assert path.exists(), f"missing corpus file: {path}"
    return json.loads(path.read_text(encoding="utf-8"))


